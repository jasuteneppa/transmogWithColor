local _, ns = ...

-- === Colour matching by closeness ===
--
-- 1.2.1 gave every appearance exactly one colour name and filtered by name.
-- A lot of WoW armour has no single name -- a red and gold gauntlet is both,
-- shaded red reads as brown to anything that ignores shading -- so the names
-- were wrong for a large share of the game in ways no boundary could fix.
--
-- This drops names. A swatch is a colour, and an appearance scores against it
-- by how much of its surface is CLOSE to that colour. The filter keeps what
-- scores above the swatch's cutoff and SORTS by score, so a piece that is
-- mostly the colour comes first and one with a trim of it comes last.
--
-- Everything numeric -- the swatches, the cutoffs, the texture-to-screen
-- calibration -- comes from Swatches.lua, generated by the tools that
-- measured it against screenshots of the Transmogrifier itself. See
-- tools/match_eval.py; this file must compute exactly what it computes.

local C = ns.MatchConstants
local SWATCHES = ns.MatchSwatches
local GROUPS = ns.MatchGroups

local swatchByKey, groupByKey = {}, {}
for i, s in ipairs(SWATCHES) do
    s.index = i
    s.neutral = math.sqrt(s.a * s.a + s.b * s.b) < C.neutralTargetChroma
    swatchByKey[s.key] = s
end
for _, g in ipairs(GROUPS) do groupByKey[g.key] = g end

-- === Colour conversion ===

local function Linear(c)
    if c <= 0.04045 then return c / 12.92 end
    return ((c + 0.055) / 1.055) ^ 2.4
end

local function F(t)
    if t > 216 / 24389 then return t ^ (1 / 3) end
    return (24389 / 27 * t + 16) / 116
end

-- sRGB 0..1 -> CIELAB (D65), the same white point as the tools.
local function RGBToLab(r, g, b)
    r, g, b = Linear(r), Linear(g), Linear(b)
    local x = (0.4124564 * r + 0.3575761 * g + 0.1804375 * b) / 0.95047
    local y = 0.2126729 * r + 0.7151522 * g + 0.0721750 * b
    local z = (0.0193339 * r + 0.1191920 * g + 0.9503041 * b) / 1.08883
    local fx, fy, fz = F(x), F(y), F(z)
    return 116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz)
end

-- Measured texture -> screen hue shift, interpolated around the circle.
local SHIFT = C.hueShift
local function HueShift(h)
    local n = #SHIFT
    for i = 1, n do
        local c1, s1 = SHIFT[i][1], SHIFT[i][2]
        local nxt = SHIFT[i % n + 1]
        local c2, s2 = nxt[1], nxt[2]
        if i == n then c2 = c2 + 360 end
        local hh = h
        if hh < SHIFT[1][1] then hh = hh + 360 end
        if hh >= c1 and hh <= c2 then
            return s1 + (s2 - s1) * (hh - c1) / (c2 - c1)
        end
    end
    return SHIFT[1][2]
end

-- A texture cluster (h, s, v from ColorData) as it appears on screen.
local function TextureToScreen(h, s, v)
    local L, a, b = RGBToLab(ns.HSVToRGB(h % 360, s, v))
    L = math.max(0, math.min(100, C.gain * L + C.offset))
    a, b = a * C.chroma, b * C.chroma
    local hue = math.deg(math.atan2(b, a)) % 360
    local t = math.rad(HueShift(hue))
    local ct, st = math.cos(t), math.sin(t)
    return L, a * ct - b * st, a * st + b * ct
end

-- How coloured a cluster is, 0..1. Whether a surface has colour at all is a
-- hard line to a person, so colour swatches count only the coloured part and
-- grey swatches only the grey part. See tools/match_eval.py.
local function Colourfulness(a, b, achromatic)
    if achromatic then return 0 end
    local c = math.sqrt(a * a + b * b)
    return math.max(0, math.min(1, (c - C.colorCLo) / (C.colorCHi - C.colorCLo)))
end

-- === Per-appearance clusters, as seen on screen ===

-- A hand correction is a colour the player SAW and picked from the strip, so
-- it is already on-screen colour and skips calibration. It stands for most of
-- the piece; whatever it did not correct keeps a smaller say.
local OVERRIDE_WEIGHT = 0.7

local function ScreenClusters(ranks, visualID)
    local out = {}
    local function add(h, s, v, w, achromatic, onScreen)
        local L, a, b
        if onScreen then
            L, a, b = RGBToLab(ns.HSVToRGB(h % 360, s, v))
        else
            L, a, b = TextureToScreen(h, s, v)
        end
        out[#out + 1] = { L, a, b, w, Colourfulness(a, b, achromatic) }
    end

    local override = ns.OverrideFor and ns.OverrideFor(visualID)
    if override and (override.main or override.accent) then
        local rest = 1
        for _, side in ipairs({ "main", "accent" }) do
            local spec = override[side]
            local w = (side == "main") and OVERRIDE_WEIGHT or (1 - OVERRIDE_WEIGHT) / 2
            if type(spec) == "number" and ranks[spec] then
                local c = ranks[spec]
                add(c[1], c[2], c[3], w, c[5], false)
                rest = rest - w
            elseif type(spec) == "table" then
                add(spec[1], spec[2], spec[3], w, spec[4], true)
                rest = rest - w
            end
        end
        local total = 0
        for i = 1, #ranks do total = total + ranks[i][4] end
        if total > 0 and rest > 0 then
            for i = 1, #ranks do
                local c = ranks[i]
                add(c[1], c[2], c[3], rest * c[4] / total, c[5], false)
            end
        end
        return out
    end

    for i = 1, #ranks do
        local c = ranks[i]
        add(c[1], c[2], c[3], c[4], c[5], false)
    end
    return out
end

-- === Scores ===

local SIG2 = 2 * C.sigma * C.sigma
local KT2 = C.neutralKTint * C.neutralKTint

local function Score(clusters, sw)
    local total, coloured, sum = 0, 0, 0
    for i = 1, #clusters do
        local c = clusters[i]
        local w, m = c[4], c[5]
        total = total + w
        coloured = coloured + w * m
        local dL, da, db = c[1] - sw.L, c[2] - sw.a, c[3] - sw.b
        if sw.neutral then
            local close = math.exp(-(dL * dL + KT2 * (da * da + db * db)) / SIG2)
            sum = sum + w * (1 - m) * close
        else
            local kl = C.kL * dL
            local close = math.exp(-(kl * kl + da * da + db * db) / SIG2)
            sum = sum + w * m * close
        end
    end
    if total <= 0 then return 0 end
    if sw.neutral then
        return (sum / total) * (1 - coloured / total)
    end
    return sum / total
end

-- visualID -> { [swatchIndex] = relative score }. Relative = score / the
-- swatch's own cutoff, so 1 means "just a match" for every swatch alike and
-- scores from different swatches can be compared and sorted together.
-- Session cache: ColorData never changes while playing; overrides do, and
-- clear it (ns.InvalidateMatchCache).
local cache = {}

function ns.InvalidateMatchCache()
    cache = {}
end

local function Relative(visualID)
    local rel = cache[visualID]
    if rel then return rel end
    local ranks = ns.ItemColors[visualID]
    if not ranks then return nil end
    local clusters = ScreenClusters(ranks, visualID)
    rel = {}
    for i, sw in ipairs(SWATCHES) do
        rel[i] = Score(clusters, sw) / sw.minScore
    end
    cache[visualID] = rel
    return rel
end

-- How well an appearance matches a strip key -- a swatch key, or a general
-- group key (its best member). >= 1 is a match. nil when there is no data.
function ns.MatchScore(visualID, key)
    local rel = Relative(visualID)
    if not rel then return nil end
    local sw = swatchByKey[key]
    if sw then return rel[sw.index] end
    local g = groupByKey[key]
    if not g then return 0 end
    local best = 0
    for _, m in ipairs(g.members) do
        local r = rel[swatchByKey[m].index]
        if r > best then best = r end
    end
    return best
end

-- The appearance's two best-matching swatches, for the tile swatches. The
-- second is skipped when it is in the same general group as the first (a red
-- piece is "red", not "red and maroon") or barely registers.
function ns.TopSwatches(visualID)
    local rel = Relative(visualID)
    if not rel then return nil end
    local first, second
    for i, r in ipairs(rel) do
        if not first or r > rel[first] then first = i end
    end
    for i, r in ipairs(rel) do
        if i ~= first and SWATCHES[i].group ~= SWATCHES[first].group
            and (not second or r > rel[second]) then
            second = i
        end
    end
    if second and rel[second] < 0.5 then second = nil end
    return SWATCHES[first], second and SWATCHES[second] or nil
end

-- === The strip's keys ===

function ns.MatchDetail()
    return (ns.state and ns.state.matchDetail == "all") and "all" or "general"
end

-- Strip order for the current detail level: { key, name, r, g, b }.
function ns.MatchStripKeys()
    local out = {}
    if ns.MatchDetail() == "all" then
        for _, s in ipairs(SWATCHES) do
            out[#out + 1] = { key = s.key, name = s.name, r = s.r, g = s.g, b = s.bl }
        end
    else
        for _, g in ipairs(GROUPS) do
            local face = swatchByKey[g.face]
            out[#out + 1] = { key = g.key, name = g.name, r = face.r, g = face.g, b = face.bl }
        end
    end
    return out
end

function ns.MatchKeyInfo(key)
    local s = swatchByKey[key]
    if s then return { key = key, name = s.name, r = s.r, g = s.g, b = s.bl } end
    local g = groupByKey[key]
    if g then
        local face = swatchByKey[g.face]
        local names = {}
        for _, m in ipairs(g.members) do names[#names + 1] = swatchByKey[m].name end
        return { key = key, name = g.name, r = face.r, g = face.g, b = face.bl,
                 members = table.concat(names, ", ") }
    end
    return nil
end

-- Switching between general and all keeps the selection: a group becomes its
-- members, and a set of members becomes their groups.
local function Translate(selection, toAll)
    if not selection then return nil end
    local out = {}
    for key in pairs(selection) do
        if toAll then
            local g = groupByKey[key]
            if g then
                for _, m in ipairs(g.members) do out[m] = true end
            elseif swatchByKey[key] then
                out[key] = true
            end
        else
            local s = swatchByKey[key]
            if s then out[s.group] = true elseif groupByKey[key] then out[key] = true end
        end
    end
    return out
end

function ns.SetMatchDetail(detail)
    if detail ~= "all" and detail ~= "general" then return end
    if ns.MatchDetail() == detail then return end
    local toAll = detail == "all"
    local mains = Translate(ns.state.primaryColors, toAll) or {}
    local sel = {}
    for key in pairs(mains) do sel[key] = { key = key } end
    ns.state.primaryColors = sel
    local accent = ns.state.accentColor
    if accent then
        local t = Translate({ [accent.key] = true }, toAll)
        local k = t and next(t)
        ns.state.accentColor = k and { key = k } or nil
    end
    ns.state.matchDetail = detail
end

-- === Hand corrections pick from the same swatches ===
--
-- Replaces Palette.lua's bucket-based versions (this file loads after it).
-- The stored form is unchanged -- { h, s, v, achromatic } -- so corrections
-- made in 1.2.1 still apply; they are read as on-screen colour.

function ns.OverridePalette()
    local out = {}
    for _, s in ipairs(SWATCHES) do
        local h, sat, v = ns.RGBToHSV(s.r, s.g, s.bl)
        out[#out + 1] = { key = s.key, h = h, s = sat, v = v }
    end
    return out
end

function ns.OverrideSpecFromKey(key)
    local s = swatchByKey[key]
    if not s then return nil end
    local h, sat, v = ns.RGBToHSV(s.r, s.g, s.bl)
    return { h, sat, v, s.neutral }
end
