"""Writes TransmogPalette/Swatches.lua from tools/palette.json and the
calibration and matching constants, so the addon matches with exactly the
numbers the offline evaluation used. Regenerate after changing any of them.

    python export_swatches.py
"""
import json
from pathlib import Path

import capture_calibrate as cc
import match_eval as me

TOOLS = Path(__file__).resolve().parent
OUT = TOOLS.parent / "TransmogPalette" / "Swatches.lua"

# The general row, in strip order: (group key, label, member swatch names,
# the member whose colour the general swatch is drawn as).
GROUPS = [
    ("g_black", "Black", ["black"], "black"),
    ("g_gray", "Gray", ["dark gray", "light gray", "slate"], "light gray"),
    ("g_white", "White", ["white"], "white"),
    ("g_red", "Red", ["maroon", "red"], "red"),
    ("g_orange", "Orange", ["orange"], "orange"),
    ("g_brown", "Brown", ["bronze", "brown"], "brown"),
    ("g_gold", "Gold", ["gold"], "gold"),
    ("g_green", "Green", ["green", "bright green", "jade"], "green"),
    ("g_blue", "Blue", ["teal", "cyan", "blue"], "blue"),
    ("g_purple", "Purple", ["violet", "purple"], "purple"),
    ("g_pink", "Pink", ["pink"], "pink"),
]


def key_of(name):
    return name.replace(" ", "")


def rgb01(hexc):
    return tuple(int(hexc[i:i + 2], 16) / 255 for i in (1, 3, 5))


def main():
    palette = json.loads((TOOLS / "palette.json").read_text(encoding="utf-8"))
    by_name = {p["name"]: p for p in palette}
    member_group = {m: g for g, _, ms, _ in GROUPS for m in ms}
    missing = [p["name"] for p in palette if p["name"] not in member_group]
    if missing:
        raise SystemExit(f"swatches with no general group: {missing}")

    gain, offset, chroma = me.FIT
    lines = [
        "local _, ns = ...",
        "",
        "-- GENERATED by tools/export_swatches.py from tools/palette.json -- do not",
        "-- hand-edit. The palette, calibration and matching constants all come from",
        "-- the offline evaluation (tools/match_eval.py), and must stay identical to",
        "-- it or the addon stops matching the way that evaluation measured.",
        "",
        "ns.MatchConstants = {",
        f"    gain = {gain}, offset = {offset}, chroma = {chroma},",
        f"    kL = {me.K_L}, sigma = {me.SIGMA},",
        f"    neutralTargetChroma = {me.NEUTRAL_TARGET_CHROMA}, neutralKTint = {me.NEUTRAL_K_TINT},",
        f"    colorCLo = {me.COLOR_C_LO}, colorCHi = {me.COLOR_C_HI}, neutralColourK = {me.NEUTRAL_COLOUR_K},",
        "    -- texture -> screen hue shift: { sector centre, degrees }",
        "    hueShift = { " + ", ".join(f"{{ {c}, {s} }}" for c, s in cc.HUE_SHIFT) + " },",
        "}",
        "",
        "-- Every swatch, in strip order. lab is the on-screen colour matched against;",
        "-- r/g/b is how the swatch is drawn; minScore is where a match stops counting.",
        "ns.MatchSwatches = {",
    ]
    for p in palette:
        r, g, b = rgb01(p["hex"])
        L, A, B = p["lab"]
        lines.append(
            f'    {{ key = "{key_of(p["name"])}", name = "{p["name"].title()}", '
            f'group = "{member_group[p["name"]]}", L = {L:.2f}, a = {A:.2f}, b = {B:.2f}, '
            f'r = {r:.3f}, g = {g:.3f}, bl = {b:.3f}, minScore = {p["min_score"]} }},')
    lines += ["}", "", "-- The general row: each matches any of its members.", "ns.MatchGroups = {"]
    for gkey, label, members, face in GROUPS:
        lines.append(f'    {{ key = "{gkey}", name = "{label}", face = "{key_of(face)}", '
                     f'members = {{ ' + ", ".join(f'"{key_of(m)}"' for m in members) + " } },")
    lines += ["}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(palette)} swatches, {len(GROUPS)} groups -> {OUT}")


if __name__ == "__main__":
    main()
